"""Детерминированный fast-роут: простые запросы БЕЗ нейросети.

Главный принцип: простые задачи не должны загружать классификатор и,
тем более, облачную LLM. Здесь — жёсткие регэкспы на однозначные
триггеры («сколько будет ...», «который час», ...). Если паттерн
совпал — запрос выполняется сразу, локально.

Если инструмент по какой-то причине не сработал (например, выражение
битое), pipeline откатывается к обычному пути (классификатор -> облако) —
fast-роут никогда не «запирает» запрос.
"""

import re

from jarvis import intents

# (паттерн по началу фразы, intent_name, имя слота-хвоста или None)
_PATTERNS = [
    # калькулятор: «сколько будет 25 * 37», «посчитай 2 плюс 2»
    (r'^(?:сколько\s+(?:будет|же\s+будет|составит)|посчитай|посчитайте|'
     r'подсчитай|вычисли|посчитать|вычислить)\b',
     'calculate', 'expression'),
    (r'^(?:который\s+час|сколько\s+(?:сейчас\s+)?времени|какое\s+сейчас\s+'
     r'время|скажи\s+время)\b', 'check_time', None),
    (r'^(?:какое\s+сегодня\s+число|какой\s+сегодня\s+день|какая\s+сегодня\s+'
     r'дата|какой\s+день\s+недели)\b', 'check_date', None),
]


def route(text):
    """Текст -> (intent_name, slots) или None, если паттерны не совпали."""
    t = (text or '').strip()
    if not t:
        return None
    for pattern, intent_name, tail_slot in _PATTERNS:
        if re.search(pattern, t, re.IGNORECASE):
            slots = intents.extract_slots(intent_name, t)
            return intent_name, slots
    return None