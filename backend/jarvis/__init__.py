"""Jarvis — модульный локальный ассистент для Linux.

Пакет разделён на слои:

    config    — пути и настройки (переопределяются переменными окружения);
    intents   — реестр намерений, уровни риска, извлечение слотов (regex);
    policy    — политика безопасности из policy.yaml;
    security  — allow/deny списки путей, подтверждения, редэкция секретов;
    ml        — локальная классификация намерений (NumPy MLP);
    tools     — безопасные инструменты (аргументы списком, без shell);
    plan      — валидация JSON-планов от облачной LLM;
    executor  — исполнение намерений и планов с учётом политики;
    cloud     — облачная LLM (возвращает ТОЛЬКО JSON-план, ничего не выполняет);
    indexer   — SQLite FTS5 индекс файлов и текста;
    sandbox   — выполнение сгенерированного кода в bubblewrap;
    pipeline  — полный цикл «текст -> ответ»;
    dbus      — D-Bus сервис (совместим с расширением GNOME Shell).
"""

