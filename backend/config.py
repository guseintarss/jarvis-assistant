# Локальный MTProto-прокси для Telegram: порт и секрет (32 hex-символа).
# Если порт уже занят этим же прокси (запущен вручную или через systemd) —
# Ева просто использует его, не поднимая второй.
TG_WSPROXY_PORT = 1443
def _load_tg_wsproxy_secret():
    """Секрет MTProto-прокси берётся по приоритету:
    1) переменная окружения JARVIS_TG_WSPROXY_SECRET;
    2) строка TG_WSPROXY_SECRET=... в ~/.config/jarvis-assistant/config;
    3) постоянный файл ~/.local/share/jarvis-assistant/tg-ws-proxy.secret
       (создаётся при первом запуске, права 600);
    4) случайный секрет на один запуск (не сохраняется)."""
    env = os.environ.get('JARVIS_TG_WSPROXY_SECRET')
    if env:
        return env
    cfg_path = os.path.expanduser('~/.config/jarvis-assistant/config')
    if os.path.exists(cfg_path):
        try:
            with open(cfg_path, encoding='utf-8') as f:
                for line in f:
                    line = line.strip()
                    if line.startswith('TG_WSPROXY_SECRET='):
                        v = line.split('=', 1)[1].strip().strip('"\'')
                        if v:
                            return v
        except OSError:
            pass
    secret_path = os.path.join(
        HOME, '.local/share/jarvis-assistant/tg-ws-proxy.secret')
    if os.path.exists(secret_path):
        try:
            with open(secret_path, encoding='utf-8') as f:
                v = f.read().strip()
                if v:
                    return v
        except OSError:
            pass
    v = secrets.token_hex(16)
    try:
        os.makedirs(os.path.dirname(secret_path), exist_ok=True)
        with open(secret_path, 'w', encoding='utf-8') as f:
            f.write(v)
        os.chmod(secret_path, 0o600)
    except OSError:
        pass
    return v

TG_WSPROXY_SECRET = _load_tg_wsproxy_secret()

